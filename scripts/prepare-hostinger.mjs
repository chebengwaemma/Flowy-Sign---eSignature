/**
 * After `npm run build` (standalone), copy static + public into the standalone folder
 * so Hostinger Node / VPS can run: node .next/standalone/server.js
 *
 * Also writes `.env` into standalone from process env / `.env.local` so Hostinger
 * runtime gets RESEND_API_KEY and other secrets without hPanel (FTP upload).
 */
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

const root = process.cwd();
const standalone = join(root, ".next", "standalone");
const staticSrc = join(root, ".next", "static");
const publicSrc = join(root, "public");

if (!existsSync(standalone)) {
  console.error("Missing .next/standalone — set output: 'standalone' and run npm run build first.");
  process.exit(1);
}

mkdirSync(join(standalone, ".next"), { recursive: true });
cpSync(staticSrc, join(standalone, ".next", "static"), { recursive: true });
if (existsSync(publicSrc)) {
  cpSync(publicSrc, join(standalone, "public"), { recursive: true });
}

/** Load .env.local into a map (does not override existing process.env). */
function loadDotEnvLocal() {
  const path = join(root, ".env.local");
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    if (!line || line.trim().startsWith("#") || !line.includes("=")) continue;
    const i = line.indexOf("=");
    const k = line.slice(0, i).trim();
    const v = line.slice(i + 1).trim();
    if (k) out[k] = v;
  }
  return out;
}

const fileEnv = loadDotEnvLocal();
function val(key) {
  return (process.env[key] || fileEnv[key] || "").trim();
}

const envKeys = [
  "MONGODB_URI",
  "AUTH_SECRET",
  "ADMIN_AUTH_SECRET",
  "NEXT_PUBLIC_APP_URL",
  "ADMIN_SEED_EMAIL",
  "ADMIN_SEED_PASSWORD",
  "RESEND_API_KEY",
  "EMAIL_FROM",
  "STRIPE_SECRET_KEY",
  "STRIPE_WEBHOOK_SECRET",
  "NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY",
  "STRIPE_PRICE_PRO_MONTHLY",
  "STRIPE_PRICE_PRO_YEARLY",
  "STRIPE_PRICE_PRO_5_MONTHLY",
  "STRIPE_PRICE_PRO_5_YEARLY",
  "STRIPE_PRICE_BUSINESS_MONTHLY",
  "STRIPE_PRICE_BUSINESS_YEARLY",
  "STRIPE_PRICE_BUSINESS_5_MONTHLY",
  "STRIPE_PRICE_BUSINESS_5_YEARLY",
  "GOOGLE_CLIENT_ID",
  "GOOGLE_CLIENT_SECRET",
];

const lines = ["# Generated by scripts/prepare-hostinger.mjs — do not commit"];
let wrote = 0;
for (const key of envKeys) {
  let v = val(key);
  if (key === "NEXT_PUBLIC_APP_URL") {
    // Emails / OAuth must never point at localhost on Hostinger.
    if (!v || /localhost|127\.0\.0\.1/i.test(v)) {
      v = "https://flowysign.com";
    }
  }
  if (!v) continue;
  lines.push(`${key}=${v}`);
  wrote += 1;
}
if (!val("EMAIL_FROM") && val("RESEND_API_KEY")) {
  lines.push("EMAIL_FROM=Flowy Sign <noreply@flowysign.com>");
  wrote += 1;
}
if (!lines.some((l) => l.startsWith("NEXT_PUBLIC_APP_URL="))) {
  lines.push("NEXT_PUBLIC_APP_URL=https://flowysign.com");
  wrote += 1;
}

writeFileSync(join(standalone, ".env"), `${lines.join("\n")}\n`, "utf8");

// Hostinger Node does not auto-load .env — use this as the startup file in hPanel.
writeFileSync(
  join(standalone, "hostinger-server.js"),
  `/* Generated — load .env then start Next standalone */
const fs = require("fs");
const path = require("path");
const envPath = path.join(__dirname, ".env");
if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, "utf8").split(/\\r?\\n/)) {
    if (!line || line.trim().startsWith("#") || !line.includes("=")) continue;
    const i = line.indexOf("=");
    const k = line.slice(0, i).trim();
    let v = line.slice(i + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    if (k && process.env[k] === undefined) process.env[k] = v;
  }
}
process.env.PORT = process.env.PORT || "3000";
process.env.HOSTNAME = process.env.HOSTNAME || "0.0.0.0";
require("./server.js");
`,
  "utf8",
);

console.log("Hostinger package ready:");
console.log("  Upload/run from .next/standalone");
console.log("  hPanel startup file: hostinger-server.js  (or: PORT=3000 node hostinger-server.js)");
console.log(`  Wrote standalone/.env with ${wrote} keys (incl. RESEND=${Boolean(val("RESEND_API_KEY"))})`);
console.log("  Required: MONGODB_URI, AUTH_SECRET, ADMIN_AUTH_SECRET, NEXT_PUBLIC_APP_URL");
